"""Generate the deterministic demo tileset PNG used by the sample asset project.

This image is project artwork generated by this script, not an asset recovered from the original
client. Run it from the repository root:

    python scripts/make-tileset.py assets/source/demo/images/terrain.png

Layout: 2 columns by 2 rows of 32 by 32 tiles, in gid order 1..4 reading left to right, top to
bottom: grass, path, water, wall. Every tile carries a bright marker in one corner so that a
horizontal, vertical or diagonal flip is visible in the editor and in the game.
"""

import struct
import sys
import zlib

TILE = 32
COLUMNS = 2
ROWS = 2
PALETTE = {
    1: (63, 125, 58, 255),
    2: (184, 154, 98, 255),
    3: (47, 95, 158, 255),
    4: (107, 107, 115, 255),
}
SHADE = {
    1: (52, 104, 48, 255),
    2: (160, 132, 82, 255),
    3: (38, 78, 132, 255),
    4: (86, 86, 94, 255),
}
MARKER = (242, 228, 168, 255)


def tile_pixel(gid, x, y):
    """Returns the colour of one pixel inside a tile, with x and y measured from the tile's top."""
    if x < 6 and y < 6:
        return MARKER
    if gid == 1:
        return SHADE[gid] if (x // 4 + y // 4) % 3 == 0 else PALETTE[gid]
    if gid == 2:
        return SHADE[gid] if y % 8 < 2 else PALETTE[gid]
    if gid == 3:
        return SHADE[gid] if (x + y * 2) % 10 < 3 else PALETTE[gid]
    if x < 2 or y < 2 or x >= TILE - 2 or y >= TILE - 2:
        return SHADE[gid]
    return PALETTE[gid]


def rows():
    width = TILE * COLUMNS
    for image_y in range(TILE * ROWS):
        row = bytearray()
        for image_x in range(width):
            gid = 1 + (image_y // TILE) * COLUMNS + image_x // TILE
            row += bytes(tile_pixel(gid, image_x % TILE, image_y % TILE))
        yield bytes(row)


def chunk(kind, payload):
    body = kind + payload
    return struct.pack(">I", len(payload)) + body + struct.pack(">I", zlib.crc32(body))


def main(destination):
    width = TILE * COLUMNS
    height = TILE * ROWS
    raw = b"".join(b"\x00" + row for row in rows())
    png = b"\x89PNG\r\n\x1a\n"
    png += chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0))
    png += chunk(b"IDAT", zlib.compress(raw, 9))
    png += chunk(b"IEND", b"")
    with open(destination, "wb") as output:
        output.write(png)
    print("wrote %s (%d bytes, %dx%d)" % (destination, len(png), width, height))


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit("Usage: make-tileset.py OUTPUT.png")
    main(sys.argv[1])
